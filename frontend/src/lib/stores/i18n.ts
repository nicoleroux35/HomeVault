import { writable, derived, get } from 'svelte/store';

type Language = 'en' | 'fr' | 'de' | 'es';

// Supported languages
const SUPPORTED_LANGUAGES: Language[] = ['en', 'fr', 'de', 'es'];

// Map browser language codes to supported languages
const LANGUAGE_MAP: Record<string, Language> = {
  en: 'en',
  fr: 'fr',
  de: 'de',
  es: 'es',
  // French variants
  'fr-fr': 'fr', 'fr-ca': 'fr', 'fr-be': 'fr',
  // German variants
  'de-de': 'de', 'de-at': 'de', 'de-ch': 'de',
  // Spanish variants
  'es-es': 'es', 'es-mx': 'es', 'es-ar': 'es',
};

function createLanguageStore() {
  // Detect language from localStorage, browser, or OS
  const detectLanguage = (): Language => {
    // 1. Check localStorage (user's explicit choice)
    const saved = localStorage.getItem('hv-language') || localStorage.getItem('language');
    if (saved && SUPPORTED_LANGUAGES.includes(saved as Language)) {
      return saved as Language;
    }

    // 2. Detect from browser/OS language
    const browserLang = (navigator.language || 'en').toLowerCase();
    
    // Try exact match first
    if (LANGUAGE_MAP[browserLang]) {
      return LANGUAGE_MAP[browserLang];
    }
    
    // Try base language (e.g., 'fr' from 'fr-FR')
    const baseLang = browserLang.split('-')[0];
    if (SUPPORTED_LANGUAGES.includes(baseLang as Language)) {
      return baseLang as Language;
    }

    // 3. Default to English
    return 'en';
  };

  const initialLanguage = detectLanguage();
  const { subscribe, set } = writable<Language>(initialLanguage);

  // Set initial language on document
  document.documentElement.setAttribute('lang', initialLanguage);

  return {
    subscribe,

    /**
     * Set language (user's explicit choice)
     */
    setLanguage(language: Language) {
      document.documentElement.setAttribute('lang', language);
      localStorage.setItem('hv-language', language);
      set(language);
    },

    /**
     * Get current detected language (without saving preference)
     */
    getDetectedLanguage(): Language {
      return initialLanguage;
    },

    /**
     * Reset to detected language (removes user preference)
     */
    resetToDetected() {
      const detected = detectLanguage();
      document.documentElement.setAttribute('lang', detected);
      localStorage.removeItem('hv-language');
      localStorage.removeItem('language');
      set(detected);
    },
  };
}

export const languageStore = createLanguageStore();

// --- Global SPA translation system ---
// The SPA fetches the flattened translation map from the backend
// (/api/translations) so a single source of truth (the TOML files) is used.
// English is always served as a fallback for missing keys.
export const translationsStore = writable<Record<string, string>>({});

let translationsLoadedFor = '';

// Whether the real backend translation map has been fetched at least once.
// The embedded `translations.en` seed below only covers the Login/Setup/
// Users/Settings namespaces, so any newer section (e.g. `desktop.*`) has no
// fallback and renders as raw keys until this resolves. Consumers (see
// App.svelte) can gate first render on this to avoid that flash.
export const translationsReady = writable(false);

async function loadTranslations(lang: string): Promise<void> {
  if (translationsLoadedFor === lang) return;
  try {
    const res = await fetch(`/api/translations?lang=${encodeURIComponent(lang)}`);
    if (res.ok) {
      translationsStore.set(await res.json());
      translationsLoadedFor = lang;
    }
  } catch (e) {
    // Network error: keep whatever is already loaded (defaults to English).
    // Deliberately don't record `translationsLoadedFor` on failure, so a
    // later call for the same language (e.g. a language switch back) retries
    // instead of being permanently skipped by the guard above.
  } finally {
    translationsReady.set(true);
  }
}

// Reload translations whenever the active language changes.
languageStore.subscribe((lang) => {
  loadTranslations(lang);
});

// Reactive translator. In markup use {$t('key')} or {$t('key', { var: 'x' })}.
// Missing keys fall back to English (provided by the backend) and finally to the key itself.
export const t = derived(translationsStore, ($tr) => {
  return (key: string, vars?: Record<string, string>): string => {
    let value = $tr[key];
    if (value === undefined || value === null) value = key;
    if (vars) {
      for (const [name, val] of Object.entries(vars)) {
        value = value.replaceAll(`%${name}%`, val);
      }
    }
    return value;
  };
});

// Plain-function variant for use inside <script> blocks.
export function translate(key: string, vars?: Record<string, string>): string {
  return get(t)(key, vars);
}

