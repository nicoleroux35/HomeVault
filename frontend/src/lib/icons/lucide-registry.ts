/** Resolve a kebab-case icon name; unknown names fall back to a neutral dot. */
export function getLucideIcon(name: string): Component<any> {
  const cleaned = name.replace(/^(phosphor|tabler)-/, '');
  return REGISTRY[cleaned] ?? REGISTRY[cleaned.replace(/_/g, '-')] ?? REGISTRY.folder;
}
