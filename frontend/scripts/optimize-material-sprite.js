#!/usr/bin/env node
/**
 * Script d'Optimisation Material Icons - Tree Shaking
 *
 * Ce script extrait uniquement les icônes Material utilisées
 * dans le code et génère un sprite minimal.
 *
 * Usage: node scripts/optimize-material-sprite.js
 *
 * Gain estimé: 4 MB → 100-200 KB (95%+ de réduction)
 */

import { readFileSync, writeFileSync } from 'fs';
import { globSync } from 'glob';
import { parseSync } from 'svgson';

console.log('🔍 Scanning codebase for used Material icons...\n');

// 1. Scanner tous les fichiers Svelte pour trouver les icônes utilisées
const files = globSync('src/**/*.{svelte,ts,js}');
const usedIcons = new Set();

files.forEach(file => {
  const content = readFileSync(file, 'utf-8');

  // Pattern 1: <Icon name="icon-name" />
  const matches1 = [...content.matchAll(/Icon\s+name=["']([^"']+)["']/g)];
  matches1.forEach(match => usedIcons.add(match[1]));

  // Pattern 2: icon: "icon-name"
  const matches2 = [...content.matchAll(/icon:\s*["']([^"']+)["']/g)];
  matches2.forEach(match => usedIcons.add(match[1]));

  // Pattern 3: {icon: 'icon-name'}
  const matches3 = [...content.matchAll(/\bicon:\s*['"]([^'"]+)['"]/g)];
  matches3.forEach(match => usedIcons.add(match[1]));
});

// Filtrer les faux positifs (variables, templates)
const validIcons = Array.from(usedIcons).filter(icon => {
  return !icon.startsWith('{') &&
         !icon.includes('$') &&
         !icon.includes('[') &&
         icon.length > 1;
});

console.log(`✓ Found ${validIcons.length} unique Material icons\n`);
console.log('Icons:', validIcons.slice(0, 20).join(', '), '...\n');

// 2. Charger le sprite complet
console.log('📦 Loading sprite-unified.svg...');
const spriteContent = readFileSync('public/sprite-unified.svg', 'utf-8');
const spriteSizeMB = (Buffer.byteLength(spriteContent) / 1024 / 1024).toFixed(2);
console.log(`   Current size: ${spriteSizeMB} MB\n`);

// 3. Parser le SVG et extraire seulement les icônes utilisées
console.log('✂️  Extracting used icons...');

// Regex pour extraire les symboles SVG
const symbolRegex = /<symbol[^>]*id="([^"]+)"[^>]*>[\s\S]*?<\/symbol>/g;
const symbols = [];
let match;

while ((match = symbolRegex.exec(spriteContent)) !== null) {
  const symbolId = match[1];
  const symbolContent = match[0];

  // Vérifier si cette icône est utilisée
  const iconName = symbolId.replace(/^(lucide-|phosphor-|tabler-)/, '');
  if (validIcons.includes(iconName) || validIcons.includes(symbolId)) {
    symbols.push(symbolContent);
  }
}

console.log(`✓ Extracted ${symbols.length} symbols\n`);

// 4. Générer le nouveau sprite minimal
const minimalSprite = `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Minimal Material Icons Sprite - HomeVault
  Generated by optimize-material-sprite.js

  Original size: ${spriteSizeMB} MB
  Optimized size: ${(symbols.join('').length / 1024).toFixed(2)} KB
  Reduction: ${(100 - (symbols.join('').length / Buffer.byteLength(spriteContent) * 100)).toFixed(1)}%

  Total icons: ${symbols.length} (from ${validIcons.length} used)
-->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" style="display:none;">
${symbols.join('\n')}
</svg>
`;

// 5. Sauvegarder le sprite optimisé
const outputPath = 'public/sprite-unified-minimal.svg';
writeFileSync(outputPath, minimalSprite, 'utf-8');

const newSizeKB = (Buffer.byteLength(minimalSprite) / 1024).toFixed(2);
const reduction = (100 - (Buffer.byteLength(minimalSprite) / Buffer.byteLength(spriteContent) * 100)).toFixed(1);

console.log('✅ Optimization complete!\n');
console.log('📊 Results:');
console.log(`   Original:  ${spriteSizeMB} MB`);
console.log(`   Optimized: ${newSizeKB} KB`);
console.log(`   Reduction: ${reduction}%\n`);
console.log(`💾 Saved to: ${outputPath}`);
console.log('\n📝 Next steps:');
console.log('   1. Rename sprite-unified.svg → sprite-unified-full.svg (backup)');
console.log('   2. Rename sprite-unified-minimal.svg → sprite-unified.svg');
console.log('   3. Update index.html if needed');
console.log('   4. Test the application');
console.log('   5. Build for production\n');
