#!/usr/bin/env bash
# Documentation coverage scanner for HomeVault.
#
# Walks the source tree, checks every file against the standard documentation
# header (see SKILL.md section "Standard file header"), and regenerates
# INDEX.md next to this script with one row per file and a status:
#
#   documented      header complete and not older than the last commit
#   to update       header present but older than the last commit (stale)
#   invalid header  header present but missing/malformed mandatory fields
#   not documented  no header at all
#
# Always scans the whole source tree so INDEX.md stays complete.
# Usage: scan.sh  (no arguments — full project scan)
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_ROOT="$(cd "$SKILL_DIR/../../.." && pwd)"
cd "$REPO_ROOT"

INDEX="$SKILL_DIR/INDEX.md"
TODAY="$(date +%d/%m/%Y)"

# DD/MM/YYYY -> YYYYMMDD (sortable), "00000000" when unparsable.
d2k() { printf '%s' "$1" | awk -F/ '{ if (NF==3 && $1 ~ /^[0-9]+$/ && $2 ~ /^[0-9]+$/ && $3 ~ /^[0-9]+$/) print $3 $2 $1; else print "00000000" }'; }

# Extract a header field value ("* Field : value" in block comments, or
# "  Field : value" inside HTML comments) from the top of a file.
get_field() {
  awk -v label="$2" '
    NR > 60 { exit }
    {
      line = $0; sub(/\r$/, "", line)
      if (line ~ "^[[:space:]]*\\*?[[:space:]]*" label "[[:space:]]*:") {
        sub("^[[:space:]]*\\*?[[:space:]]*" label "[[:space:]]*:[[:space:]]*", "", line)
        print line
        exit
      }
    }' "$1"
}

FILES="$(find src frontend/src tests \( -name '*.rs' -o -name '*.ts' -o -name '*.svelte' \) \
           -not -path '*/target/*' -not -path '*/node_modules/*' \
           -not -path '*/components/ui/*' | LC_ALL=C sort)"

TMP="$(mktemp)"
SUMMARY="$(mktemp)"
trap 'rm -f "$TMP" "$SUMMARY"' EXIT

declare -A ROWS
N_OK=0; N_STALE=0; N_BAD=0; N_MISSING=0; N_TOTAL=0

while IFS= read -r f; do
  [ -z "$f" ] && continue
  N_TOTAL=$((N_TOTAL + 1))

  gdate="$(git log -1 --format=%ad --date=format:%d/%m/%Y -- "$f" 2>/dev/null || true)"
  # No commit yet (untracked/new file): git cannot tell whether the file
  # changed since it was documented, so never flag it stale — a missing
  # header is still reported by the field checks below.
  [ -z "$gdate" ] && gdate=""

  first="$(LC_ALL=C head -c 8 -- "$f" | tr -d '\0')"
  file_field="$(get_field "$f" "File")"
  created="$(get_field "$f" "Created")"
  version="$(get_field "$f" "Version")"
  lastmod="$(get_field "$f" "Last modified")"

  if [ -z "$file_field" ] || { [ "${first:0:2}" != "/*" ] && [ "${first:0:4}" != "<!--" ]; }; then
    status="not documented"; N_MISSING=$((N_MISSING + 1)); v="—"; lm="—"
  elif [ "$file_field" != "$(basename -- "$f")" ] || [ -z "$created" ] || [ -z "$version" ] || [ -z "$lastmod" ]; then
    status="invalid header"; N_BAD=$((N_BAD + 1)); v="${version:-—}"; lm="${lastmod:-—}"
  else
    v="$version"
    lm="${lastmod%%[[:space:]]by[[:space:]]*}"
    if [ -n "$gdate" ] && [ "$(d2k "$lm")" -lt "$(d2k "$gdate")" ]; then
      status="to update"; N_STALE=$((N_STALE + 1))
    else
      status="documented"; N_OK=$((N_OK + 1))
    fi
  fi

  row="| \`$f\` | $status | $v | $lm | ${gdate:--} |"
  dir="$(dirname -- "$f")"
  ROWS["$dir"]="${ROWS["$dir"]:-}${row}"$'\n'
done <<< "$FILES"

{
  echo "# Source documentation index"
  echo
  echo "Auto-generated by \`.agents/skills/doc-sources/scripts/scan.sh\` — do not"
  echo "edit by hand; re-run the script to refresh. Used by the doc-sources"
  echo "skill to track documentation coverage of every source file."
  echo
  echo "**Last scan:** $TODAY"
  echo
  echo "**Coverage:** $N_OK documented · $N_STALE to update · $N_BAD invalid header · $N_MISSING not documented — $N_TOTAL files"
  echo
  echo "Status legend: \`documented\` = standard header complete and up to date ·"
  echo "\`to update\` = header older than the last commit · \`invalid header\` ="
  echo "mandatory field missing or File name mismatch · \`not documented\` = no header."
} > "$TMP"

for dir in $(printf '%s\n' "${!ROWS[@]}" | LC_ALL=C sort); do
  {
    echo
    echo "## $dir"
    echo
    echo "| File | Status | Version | Last modified | Last commit |"
    echo "|------|--------|---------|---------------|-------------|"
    printf '%s' "${ROWS["$dir"]}"
  } >> "$TMP"
done

mv "$TMP" "$INDEX"
echo "Wrote $INDEX — $N_OK documented, $N_STALE to update, $N_BAD invalid header, $N_MISSING not documented ($N_TOTAL files)"
