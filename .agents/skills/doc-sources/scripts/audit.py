#!/usr/bin/env python3
"""Documentation audit for HomeVault — verifies every scanned source file
against the doc-sources skill's standard: banner presence/uniqueness, field
completeness, git-date consistency, attribution rules, English-only headers,
the Rust nested-comment trap, and the no-third-party-NAS-product rule.

Run from anywhere: python3 .agents/skills/doc-sources/scripts/audit.py
(Git-date checks ignore docs-campaign commits, so a pure documentation
commit never makes the tree look stale.)"""
import os, re, subprocess, sys
from datetime import datetime

ROOT = "/media/nicolas/500GB/Projets/Homevault"
os.chdir(ROOT)

FORBIDDEN = re.compile(r"\b(Claude(?!\.md)|ChatGPT|GPT-?\d?|Copilot|AI-generated|generated by AI|written by AI)\b", re.I)
# Third-party NAS / self-hosting platform names — never cite them in code
# or docs (functional dependency names like Docker/restic/Avahi are fine;
# installable catalog app names in fixtures are fine).
NAS_PRODUCTS = re.compile(r"\b(umbrelOS?|TrueNAS|OpenMediaVault|Synology|DSM|CasaOS|Unraid|QNAP|Rockstor|Amahi|YunoHost|Cloudron|CapRover|DietPi|Runtipi|Proxmox)\b", re.I)
FRENCH = re.compile(r"\b(les?|des?|une?|pour|avec|dans|sur\s+le|fichiers?|permettre|afin|ainsi|celle|celui|était|sont)\b", re.I)
DATE = re.compile(r"^\d{2}/\d{2}/\d{4}$")
VER = re.compile(r"^\d+\.\d+\.\d+$")

def files():
    out = subprocess.run(
        ["find", "src", "frontend/src", "tests", "-name", "*.rs", "-o", "-name", "*.ts", "-o", "-name", "*.svelte"],
        capture_output=True, text=True).stdout.splitlines()
    return [f for f in sorted(out) if "/target/" not in f and "/node_modules/" not in f
            and "/components/ui/" not in f]

def git_commits(path):
    r = subprocess.run(["git", "log", "--format=%ad:%s", "--date=format:%d/%m/%Y", "--", path],
                       capture_output=True, text=True)
    rows = [l.split(":", 1) for l in r.stdout.strip().splitlines() if l]
    return [(d, s) for d, s in rows]

def git_last(path):
    """Last commit date, ignoring the docs-campaign commits (subject 'docs:')."""
    for d, s in git_commits(path):
        if not s.startswith("docs:"):
            return d
    return ""

def git_first(path):
    """First commit date, ignoring the docs-campaign commits."""
    commits = git_commits(path)
    return commits[-1][0] if commits and not commits[-1][1].startswith("docs:") else ""

def ordinal(d):
    try:
        return datetime.strptime(d, "%d/%m/%Y").toordinal()
    except ValueError:
        return -1

def parse_header(text, is_svelte):
    """Return dict of fields + section bodies from the first banner."""
    fields = {}
    sections = {}
    cur = None
    lines = text.splitlines()
    terminator = text.find("-->") if is_svelte else text.find("*/")
    limit = text[:terminator].count("\n") + 1 if terminator != -1 else 60
    for ln in lines[:limit]:
        m = re.match(r"^\s*\*?\s*(File|Author|Created|Last modified|Version)\s*:\s*(.+?)\s*$", ln)
        if m:
            fields[m.group(1)] = m.group(2); cur = None; continue
        m = re.match(r"^\s*\*?\s*(Description|Dependencies|Usage)\s*:\s*$", ln)
        if m:
            cur = m.group(1); sections[cur] = []; continue
        if cur and (ln.startswith(" *") or (is_svelte and ln.startswith("     "))):
            if re.match(r"^\s*\*?\s*=+$", ln): continue
            sections[cur].append(ln.lstrip(" *").lstrip())
        elif cur and ln.strip() and not ln.strip().startswith("*"):
            sections[cur].append(ln.strip())
    return fields, sections

issues = {}
def add(cat, path, detail=""):
    issues.setdefault(cat, []).append(f"{path}" + (f" — {detail}" if detail else ""))

allf = files()
tracked_unborn = 0
for path in allf:
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read(8000)
    base = os.path.basename(path)
    is_svelte = path.endswith(".svelte")
    lines = text.splitlines()
    first = lines[0].lstrip() if lines else ""
    # 1. banner presence + placement
    if not (first.startswith("/*") or first.startswith("<!--")):
        add("banner missing/misplaced", path, f"first line: {first[:40]!r}"); continue
    # 2. uniqueness
    n = sum(1 for ln in lines[:80] if re.match(r"^\s*\*?\s*File\s*:\s*\S", ln))
    if n != 1:
        add("banner not unique", path, f"{n} 'File:' fields in first 80 lines")
    fields, sections = parse_header(text, is_svelte)
    # 3. mandatory fields
    for k in ("File", "Author", "Created", "Last modified", "Version"):
        if k not in fields:
            add("missing field", path, k); 
    if any(k not in fields for k in ("File","Author","Created","Last modified","Version")):
        continue
    # 4. File == basename
    if fields["File"] != base:
        add("File != basename", path, fields["File"])
    # 5. author
    if fields["Author"] != "Nicolas Le Roux":
        add("author mismatch", path, fields["Author"])
    # 6. date formats
    lm = fields["Last modified"].split(" by ")[0].strip()
    for label, d in (("Created", fields["Created"]), ("Last modified", lm)):
        if not DATE.match(d):
            add("bad date format", path, f"{label}={d!r}")
    # 7. git consistency
    gl = git_last(path)
    if gl and lm != gl:
        add("Last modified != last commit", path, f"header={lm} git={gl}")
    gc = git_first(path)
    if gc and fields["Created"] != gc:
        add("Created != first commit", path, f"header={fields['Created']} git={gc}")
    if not gl:
        tracked_unborn += 1
    # 8. chronology
    if 0 <= ordinal(fields["Created"]) < ordinal(lm) or ordinal(fields["Created"]) > ordinal(lm):
        if ordinal(fields["Created"]) > ordinal(lm):
            add("Created after Last modified", path, f"{fields['Created']} > {lm}")
    # 9. version
    if not VER.match(fields["Version"]):
        add("bad version", path, fields["Version"])
    # 10-12. sections
    for s in ("Description", "Dependencies", "Usage"):
        body = [l for l in sections.get(s, []) if l]
        if not body:
            add("empty section", path, s)
    # 13. attribution rules
    if FORBIDDEN.search(text[:3000]):
        add("forbidden attribution", path, FORBIDDEN.search(text[:3000]).group(0))
    # 13b. no third-party NAS platform names anywhere in the file
    with open(path, encoding="utf-8", errors="replace") as f:
        full = f.read()
    mn = NAS_PRODUCTS.search(full)
    if mn:
        line_no = full[:mn.start()].count("\n") + 1
        add("NAS product name", path, f"line {line_no}: {mn.group(0)!r}")
    # 14. French in header (section bodies only; "Le Roux" is a name)
    head_text = "\n".join(l for body in sections.values() for l in body)
    m = FRENCH.search(head_text)
    if m:
        add("french in header", path, m.group(0))
    # 15. nested /* trap in banner
    banner_end = text.find("*/") if not is_svelte else text.find("-->")
    if banner_end != -1 and "/*" in text[3:banner_end]:
        add("nested /* in banner", path)

# report
total = len(allf)
print(f"Files audited: {total}")
if not issues:
    print("RESULT: ALL CHECKS PASSED")
else:
    print("RESULT: ISSUES FOUND")
    for cat in sorted(issues):
        print(f"\n== {cat} ({len(issues[cat])})")
        for item in issues[cat][:20]:
            print("  ", item)
        if len(issues[cat]) > 20:
            print(f"   ... +{len(issues[cat])-20} more")
print(f"\n(untracked files without git history: {tracked_unborn})")
